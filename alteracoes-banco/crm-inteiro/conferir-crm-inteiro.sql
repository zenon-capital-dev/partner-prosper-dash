  ('tempo_real','public.sales',NULL,'20260703215121'),
  ('tempo_real','public.sales_goals',NULL,'20260703215121'),
  ('extensao','pg_trgm',NULL,'20260508030153')
),
banco(tipo, objeto, extra) AS (
  SELECT 'tabela', n.nspname || '.' || c.relname, CASE WHEN c.relrowsecurity THEN NULL ELSE 'sem_rls' END
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE c.relkind IN ('r','p') AND n.nspname IN ('public','private')
  UNION ALL
  SELECT 'coluna', n.nspname || '.' || c.relname || '.' || a.attname, NULL
    FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE c.relkind IN ('r','p') AND n.nspname IN ('public','private') AND a.attnum > 0 AND NOT a.attisdropped
  UNION ALL
  SELECT 'funcao', n.nspname || '.' || p.proname || '#' || p.pronargs, md5(replace(p.prosrc, E'\r', ''))
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
   WHERE n.nspname IN ('public','private')
     AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
  UNION ALL
  SELECT 'gatilho', n.nspname || '.' || c.relname || ':' || t.tgname, NULL
    FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE NOT t.tgisinternal AND n.nspname IN ('public','private','auth','storage')
     AND (n.nspname IN ('public','private') OR EXISTS (SELECT 1 FROM esperado e WHERE e.tipo = 'gatilho' AND e.objeto = n.nspname || '.' || c.relname || ':' || t.tgname))
  UNION ALL
  SELECT 'politica', p.schemaname || '.' || p.tablename || '|' || p.policyname, NULL
    FROM pg_policies p
   WHERE p.schemaname IN ('public','private') OR (p.schemaname = 'storage' AND p.tablename = 'objects')
  UNION ALL
  SELECT 'visao', n.nspname || '.' || c.relname, NULL
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE c.relkind IN ('v','m') AND n.nspname IN ('public','private')
  UNION ALL
  SELECT 'enum', n.nspname || '.' || t.typname || ':' || e.enumlabel, NULL
    FROM pg_enum e JOIN pg_type t ON t.oid = e.enumtypid JOIN pg_namespace n ON n.oid = t.typnamespace
  UNION ALL
  SELECT 'indice', schemaname || '.' || indexname, NULL
    FROM pg_indexes WHERE schemaname IN ('public','private','storage','auth')
  UNION ALL
  SELECT 'pasta', id, NULL FROM storage.buckets
  UNION ALL
  SELECT 'tempo_real', schemaname || '.' || tablename, NULL
    FROM pg_publication_tables WHERE pubname = 'supabase_realtime'
  UNION ALL
  SELECT 'extensao', extname, NULL FROM pg_extension
),
conferido AS (
  SELECT e.tipo, e.objeto, e.migration,
    CASE
      WHEN NOT EXISTS (SELECT 1 FROM banco b WHERE b.tipo = e.tipo AND b.objeto = e.objeto) THEN 'FALTA'
      WHEN e.tipo = 'funcao' AND NOT EXISTS (SELECT 1 FROM banco b WHERE b.tipo = e.tipo AND b.objeto = e.objeto AND b.extra = e.extra) THEN 'VERSAO DIFERENTE'
      WHEN e.tipo = 'tabela' AND EXISTS (SELECT 1 FROM banco b WHERE b.tipo = e.tipo AND b.objeto = e.objeto AND b.extra = 'sem_rls') THEN 'SEM RLS'
      ELSE 'OK'
    END AS situacao
  FROM esperado e
),
so_no_banco AS (
  SELECT DISTINCT b.tipo, b.objeto, '-' AS migration, 'SO NO BANCO' AS situacao
    FROM banco b
   WHERE b.tipo IN ('tabela','coluna','funcao','gatilho','politica','visao','pasta')
     AND NOT EXISTS (SELECT 1 FROM esperado e WHERE e.tipo = b.tipo AND e.objeto = b.objeto)
)
SELECT ordem, tipo, objeto, situacao, migration
FROM (
  SELECT 0 AS ordem, 'RESUMO' AS tipo,
         tipo || ': ' || count(*) FILTER (WHERE situacao = 'OK') || ' de ' || count(*) AS objeto,
         CASE WHEN bool_and(situacao = 'OK') THEN 'OK' ELSE 'REVISAR' END AS situacao,
         '-' AS migration
    FROM conferido
   GROUP BY tipo
  UNION ALL
  SELECT 1, tipo, objeto, situacao, migration FROM conferido WHERE situacao <> 'OK'
  UNION ALL
  SELECT 2, tipo, objeto, situacao, migration FROM so_no_banco
) x
ORDER BY ordem, situacao, tipo, objeto;